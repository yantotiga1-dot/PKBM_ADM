export const INITIAL_ATTENDANCE: AttendanceRecord[] = RECENT_DATES.flatMap(
  (tanggal, dIdx) =>
    INITIAL_LEARNERS.map((learner, lIdx) => {
      let status: AttendanceRecord['status'] = 'Hadir';
      if (learner.id === 'WB-2026-005' && (dIdx === 2 || dIdx === 6 || dIdx === 9 || dIdx === 10)) {
        status = 'Alfa';
      } else if (learner.id === 'WB-2026-004' && (dIdx === 4 || dIdx === 8 || dIdx === 11)) {
        status = 'Izin';
      } else if (learner.id === 'WB-2026-003' && dIdx === 5) {
        status = 'Sakit';
      } else if (learner.id === 'WB-BTU-003' && (dIdx === 1 || dIdx === 5 || dIdx === 9)) {
        status = 'Alfa';
      }

      return {
        id: `ABS-${tanggal}-${learner.id}`,
        institutionId: learner.institutionId,
        tanggal,
        learnerId: learner.id,
        status,
        modePembelajaran: MODES[dIdx % 3],
        waktuCatat: `08:${String(5 + (lIdx % 9) * 3).padStart(2, '0')}`,
        sumber: 'Manual',
        catatan:
          status === 'Izin'
            ? 'Izin keperluan keluarga'
            : status === 'Sakit'
            ? 'Surat keterangan istirahat'
            : status === 'Alfa'
            ? 'Belum ada konfirmasi'
            : '',
      };
    })
);

